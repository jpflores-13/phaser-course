# Sound effects: short synthesised WAVs (mono, 22.05 kHz, 16-bit)
# --------------------------------------------------------------------------

RATE = 22050


def tone(freqs, dur, shape="square", vol=0.35, decay=6.0):
    t = np.linspace(0, dur, int(RATE * dur), endpoint=False)
    f = np.interp(t, np.linspace(0, dur, len(freqs)), freqs)
    phase = 2 * np.pi * np.cumsum(f) / RATE
    if shape == "square":
        wave_ = np.sign(np.sin(phase))
    elif shape == "triangle":
        wave_ = 2 / np.pi * np.arcsin(np.sin(phase))
    else:
        wave_ = np.sin(phase)
    env = np.exp(-decay * t / dur) * np.minimum(1, t * 400)
    return wave_ * env * vol


def noise(dur, vol=0.4, decay=8.0, smooth=1):
    rng = np.random.default_rng(80)
    n = rng.uniform(-1, 1, int(RATE * dur))
    if smooth > 1:
        n = np.convolve(n, np.ones(smooth) / smooth, mode="same")
    t = np.linspace(0, 1, len(n))
    return n * np.exp(-decay * t) * vol


def seq(*parts):
    return np.concatenate(parts)


def write_wav(path: Path, samples: np.ndarray) -> None:
    samples = np.clip(samples, -1, 1)
    data = (samples * 32767).astype("<i2").tobytes()
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(data)


