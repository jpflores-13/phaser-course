def tileset() -> Image.Image:
    img = Image.new("RGBA", (TILE * 3, TILE * 3), (0, 0, 0, 0))
    for i, (name, _) in enumerate(TILES):
        img.paste(draw_tile(name), ((i % 3) * TILE, (i // 3) * TILE))
    return img


# --------------------------------------------------------------------------
# Maps (Tiled JSON, .tmj). Built from a few rectangles so the layout is easy
# to change. Open them in Tiled to edit by hand.
# --------------------------------------------------------------------------


class Floor:
    def __init__(self, width: int, height: int):
        self.w, self.h = width, height
        self.walls = [[0] * width for _ in range(height)]
        self.decor = [[0] * width for _ in range(height)]
        self.objects: list[dict] = []
        for x in range(width):
            self.walls[0][x] = self.walls[height - 1][x] = GID["wall"]
        for y in range(height):
            self.walls[y][0] = self.walls[y][width - 1] = GID["wall"]

    def vwall(self, x: int, gaps: list[range]) -> None:
        for y in range(self.h):
            if not any(y in g for g in gaps):
                self.walls[y][x] = GID["wall"]

    def hwall(self, y: int, x0: int, x1: int, gaps: list[range]) -> None:
        for x in range(x0, x1 + 1):
            if not any(x in g for g in gaps):
                self.walls[y][x] = GID["wall"]

    def bench(self, y: int, x0: int, x1: int, extras: dict[int, str] | None = None) -> None:
        extras = extras or {}
        for x in range(x0, x1 + 1):
            self.walls[y][x] = GID[extras.get(x, "bench")]

    def put(self, layer: str, x: int, y: int, name: str) -> None:
        (self.walls if layer == "walls" else self.decor)[y][x] = GID[name]

    def obj(self, kind: str, tx: float, ty: float, **props) -> None:
        self.objects.append(
            {
                "id": len(self.objects) + 1,
                "name": kind,
                "type": kind,
                "x": tx * TILE + TILE / 2,
                "y": ty * TILE + TILE / 2,
                "width": 0,
                "height": 0,
                "point": True,
                "rotation": 0,
                "visible": True,
                "properties": [
                    {"name": k, "type": "float" if isinstance(v, float) else ("int" if isinstance(v, int) else "string"), "value": v}
                    for k, v in props.items()
                ],
            }
        )

    def to_tiled(self) -> dict:
        floor = [GID["floor"] if (x + y) % 2 == 0 else GID["floor-alt"] for y in range(self.h) for x in range(self.w)]
        return {
            "type": "map",
            "version": "1.10",
            "tiledversion": "1.11.2",
            "orientation": "orthogonal",
            "renderorder": "right-down",
            "infinite": False,
            "width": self.w,
            "height": self.h,
            "tilewidth": TILE,
            "tileheight": TILE,
            "nextlayerid": 5,
            "nextobjectid": len(self.objects) + 1,
            "layers": [
                self._layer(1, "floor", floor),
                self._layer(2, "decor", [v for row in self.decor for v in row]),
                self._layer(3, "walls", [v for row in self.walls for v in row]),
                {
                    "id": 4,
                    "name": "objects",
                    "type": "objectgroup",
                    "draworder": "topdown",
                    "opacity": 1,
                    "visible": True,
                    "x": 0,
                    "y": 0,
                    "objects": self.objects,
                },
            ],
            "tilesets": [
                {
                    "firstgid": 1,
                    "name": "lab",
                    "image": "../tiles/lab.png",
                    "imagewidth": TILE * 3,
                    "imageheight": TILE * 3,
                    "tilewidth": TILE,
                    "tileheight": TILE,
                    "columns": 3,
                    "tilecount": len(TILES),
                    "margin": 0,
                    "spacing": 0,
                    "tiles": [
                        {"id": i, "properties": [{"name": "collides", "type": "bool", "value": collides}]}
                        for i, (_, collides) in enumerate(TILES)
                    ],
                }
            ],
        }

    def _layer(self, lid: int, name: str, data: list[int]) -> dict:
        return {
            "id": lid,
            "name": name,
            "type": "tilelayer",
            "width": self.w,
            "height": self.h,
            "opacity": 1,
            "visible": True,
            "x": 0,
            "y": 0,
            "data": data,
        }


